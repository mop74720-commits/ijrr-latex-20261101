    steps=int(8*spec['omega0_rad_s']/h0)//8*8
    value=dict(schema_version=1,object='Original H* plant; H0 nominal desired trajectory; learned conservative force residual matching',
        seeds=SEEDS,initials_per_seed=8,policies=POLICIES,methods=METHODS,
        residual='rhat=J grad(Hhat)-J grad(H0); true momentum r=-d*(sin(theta)-theta)',
        physical_port='b(q)=d*cos(theta), scalar u=By/B0, max abs(u)=.2',
        compensation='u_ff=-dot(b,rhat_p)/dot(b,b); oracle=(sin(theta)-theta)/cos(theta)',
        feedback='u=clip(u_ref-kp*(sin(theta)-sin(theta_ref))-kd*(v-v_ref)+u_ff,-.2,.2)',
        reference='H0 with same bounded smooth u_ref, zero initial, independent DOP853; fixed before outcomes',
        kp=1.,kd=.5,base_h_tau=h0,base_steps=steps,duration_seconds=steps*h0/spec['omega0_rad_s'],
        primary_step_divisors=[1,2],zero_initial_response_step_divisors=[.5,1,2,4],
        output_stride_in_h0=8,weights='Original full12-trajectory/10k GR/GC, no retraining or outcome selection',
        discarded_components='Kinematic residual and momentum residual orthogonal to b are recorded; never independently actuated',
        structure='Exact potential-kick type2 generator S=q.P-ell*u*sin(d.q); fixed u versus sampled feedback differentiated separately',
        original_generator_instance='G: phi^[1]_(h,u)(Q,P)=-h*H*(Q,-P)+h*u*sin(d.Q), gradient=(Delta_p,Delta_q), Q=q_mid and P=-p_mid; independently solved and checked equal to I. G shares I trajectories only after equivalence checks; not an independent advantage.',
        arbitrary_control_condition='A state-vector addition to a generating gradient must be integrable: symmetric Jacobian on a simply connected domain. Sampled feedback is separately differentiated.',
        primary_metrics=['tracking_tip_rmse_mm','tracking_state_relative_l2','tail_half_tracking_tip_rmse_mm'],
        secondary_metrics=['integral_u_squared_seconds','max_abs_u','saturation_fraction','residual_projection_errors','work_energy_defect'],
        statistics='8 trajectories per seed block, then5 seed mean/sampleSD; time points not independent replicates',
        scope='Numerical compensation of a known simulation mismatch using independently trained weights; not experimental disturbance identification or general arbitrary-vector control',
        all_failures_retained=True,inputs=registry)
